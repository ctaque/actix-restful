/// A macro to generate the http routes on the Actix app :
///
/// ```ignore
///
/// #[actix_web::main]
/// async fn main() -> std::io::Result<()>{
///    actix_web::HttpServer::new(|| {
///        actix_web::App::new()
///            .service(actix_web::web::scope("/v1").configure(gen_endpoint!(Item, NewItem, UpdatableItem)))
///            .app_data(actix_web::web::Data::new(AppState{}))
///    })
///        .bind(("127.0.0.1", 8085))?
///        .run()
///        .await
/// }
/// ```
///
/// If the attribute macro `actix_restful_info` is used with these parameters :
///
/// #[actix_restful_info(path = "item")]
///
///
/// The macro gen_endpoint! will generate 5 routes on the actix App :
///
/// - GET /v1/item/{id}
/// - GET /v1/item
/// - POST /v1/item
/// - PUT /v1/item/{id}
/// - DELETE /v1/item/{id}

#[macro_export]
macro_rules! gen_endpoint {
    ($model:ident, $new_model:ident, $updatable_model:ident) => {{
        let path = <$model as $crate::RestfulPathInfo>::path();
        use $crate::__private::actix_web::web;
        move |cfg: &mut web::ServiceConfig| {
            cfg.route(
                "/{path}/{id}".replace("{path}", &path).as_str(),
                web::get().to(<$model as $crate::HttpFindListDelete<_, _, _, _, _>>::http_find),
            )
            .route(
                "/{path}/{id}".replace("{path}", &path).as_str(),
                web::delete().to(<$model as $crate::HttpFindListDelete<_, _, _, _, _>>::http_delete),
            )
            .route(
                "/{path}/{id}".replace("{path}", &path).as_str(),
                web::put().to(<$updatable_model as $crate::HttpUpdate<_, _, _>>::http_update),
            )
            .route(
                "/{path}".replace("{path}", &path).as_str(),
                web::get().to(<$model as $crate::HttpFindListDelete<_, _, _, _, _>>::http_list),
            )
            .route(
                "/{path}".replace("{path}", &path).as_str(),
                web::post().to(<$new_model as $crate::HttpCreate<_, _>>::http_create),
            );
        }
    }};
}

/// Same as `gen_endpoint!`, on an [apistos](https://docs.rs/apistos) app: the 5 routes are
/// added to its OpenAPI document (requires the `openapi` feature).
///
/// The models, their query structs and the list / delete results must implement
/// `apistos::ApiComponent` (usually `#[derive(JsonSchema, ApiComponent)]`).
///
/// ```ignore
///
/// use apistos::app::OpenApiWrapper;
/// use apistos::spec::Spec;
///
/// #[actix_web::main]
/// async fn main() -> std::io::Result<()>{
///    actix_web::HttpServer::new(|| {
///        actix_web::App::new()
///            .document(Spec::default())
///            .service(apistos::web::scope("/v1").configure(gen_documented_endpoint!(Item, NewItem, UpdatableItem)))
///            .app_data(actix_web::web::Data::new(AppState{}))
///            .build("/openapi.json")
///    })
///        .bind(("127.0.0.1", 8085))?
///        .run()
///        .await
/// }
/// ```
#[cfg(feature = "openapi")]
#[macro_export]
macro_rules! gen_documented_endpoint {
    ($model:ident, $new_model:ident, $updatable_model:ident) => {{
        let path = <$model as $crate::RestfulPathInfo>::path();
        use std::marker::PhantomData;
        use $crate::openapi::{self, apistos::web};
        move |cfg: &mut web::ServiceConfig| {
            let item_path = "/{path}/{id}".replace("{path}", &path);
            let collection_path = "/{path}".replace("{path}", &path);
            cfg.route(
                &item_path,
                web::get().to(openapi::find(
                    PhantomData::<$model>,
                    <$model as $crate::HttpFindListDelete<_, _, _, _, _>>::http_find,
                )),
            )
            .route(
                &item_path,
                web::delete().to(openapi::delete(
                    PhantomData::<$model>,
                    <$model as $crate::HttpFindListDelete<_, _, _, _, _>>::http_delete,
                )),
            )
            .route(
                &item_path,
                web::put().to(openapi::update(
                    PhantomData::<($model, $updatable_model)>,
                    <$updatable_model as $crate::HttpUpdate<_, _, _>>::http_update,
                )),
            )
            .route(
                &collection_path,
                web::get().to(openapi::list(
                    PhantomData::<$model>,
                    <$model as $crate::HttpFindListDelete<_, _, _, _, _>>::http_list,
                )),
            )
            .route(
                &collection_path,
                web::post().to(openapi::create(
                    PhantomData::<($model, $new_model)>,
                    <$new_model as $crate::HttpCreate<_, _>>::http_create,
                )),
            );
        }
    }};
}

/// A macro to generate the route of a `HasMany` relation on the Actix app, to register in the
/// same scope as the parent model (Actix does not fall through between scopes sharing a prefix):
///
/// ```ignore
///
/// actix_web::web::scope("/v1")
///     .configure(gen_endpoint!(Project, NewProject, UpdatableProject))
///     .configure(gen_relation_endpoint!(ProjectBooks))
/// ```
///
/// With `RELATION = "books"` on a relation whose parent has the path `project`, the macro
/// generates the route:
///
/// - GET /v1/project/{id}/books
#[macro_export]
macro_rules! gen_relation_endpoint {
    ($relation:ty) => {{
        use $crate::__private::actix_web::web;
        move |cfg: &mut web::ServiceConfig| {
            cfg.route(
                &$crate::__private::relation_route::<$relation>(),
                web::get().to($crate::__private::http_list_related::<$relation>),
            );
        }
    }};
}

/// Same as `gen_relation_endpoint!`, on an [apistos](https://docs.rs/apistos) app: the route is
/// added to its OpenAPI document, tagged with the path of the parent model (requires the
/// `openapi` feature).
///
/// The id, query and result types of the relation must implement `apistos::ApiComponent`.
#[cfg(feature = "openapi")]
#[macro_export]
macro_rules! gen_documented_relation_endpoint {
    ($relation:ty) => {{
        use std::marker::PhantomData;
        use $crate::openapi::{self, apistos::web};
        move |cfg: &mut web::ServiceConfig| {
            cfg.route(
                &$crate::__private::relation_route::<$relation>(),
                web::get().to(openapi::list_related(
                    PhantomData::<$relation>,
                    $crate::__private::http_list_related::<$relation>,
                )),
            );
        }
    }};
}
